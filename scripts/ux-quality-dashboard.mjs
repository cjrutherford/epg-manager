#!/usr/bin/env node
/**
 * Generate the static UX quality dashboard from docs/quality-evidence.json.
 * CI can upload the same page as an artifact; the evidence file is the source
 * of truth so the numbers cannot drift from the tests silently.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const evidence = JSON.parse(fs.readFileSync(path.join(root, 'docs/quality-evidence.json'), 'utf8'));
const m = evidence.metrics;
const pct = value => value === null || value === undefined ? '—' : `${(value * 100).toFixed(1)}%`;
const statusClass = status => status === 'pass' || status === 'resolved' ? 'ok'
    : status === 'in-progress' ? 'warn' : 'open';
const card = (label, value, note = '') => `<div class="metric"><span>${label}</span><strong>${value}</strong><small>${note}</small></div>`;

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Tuner Daemon — UX quality dashboard</title>
<style>
:root{--bg:#050505;--panel:#0f0d0b;--line:rgba(255,255,255,.1);--text:#f5f2eb;--muted:#b5ac9d;--amber:#e8a854;--green:#7fb685;--red:#c75d5d;--blue:#6ba3d6}
*{box-sizing:border-box}body{margin:0;background:var(--bg);color:var(--text);font:15px/1.55 'Libre Franklin',system-ui,sans-serif}
main{max-width:1120px;margin:0 auto;padding:48px 24px 80px}h1{font-size:2rem;margin:0 0 6px}h2{font-size:1.2rem;margin:40px 0 12px;border-top:1px solid var(--line);padding-top:22px}
p{color:var(--muted);max-width:78ch}.eyebrow{font-size:.72rem;letter-spacing:.14em;text-transform:uppercase;color:var(--amber);font-weight:700}
.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(160px,1fr));gap:12px;margin:18px 0}
.metric{background:var(--panel);border:1px solid var(--line);border-radius:10px;padding:14px}
.metric span{display:block;font-size:.72rem;text-transform:uppercase;letter-spacing:.08em;color:var(--muted)}
.metric strong{display:block;font-size:1.6rem;margin:4px 0}.metric small{color:var(--muted);font-size:.74rem}
table{width:100%;border-collapse:collapse;font-size:.88rem}th,td{text-align:left;padding:10px 12px;border-bottom:1px solid var(--line);vertical-align:top}
th{color:var(--muted);font-weight:600}.pill{display:inline-block;border-radius:999px;padding:2px 9px;font-size:.7rem;font-weight:700;text-transform:uppercase;letter-spacing:.06em}
.ok{background:rgba(127,182,133,.16);color:var(--green)}.warn{background:rgba(212,168,67,.16);color:var(--amber)}.open{background:rgba(199,93,93,.16);color:var(--red)}
.note{border-left:3px solid var(--amber);background:rgba(232,168,84,.06);padding:12px 16px;border-radius:0 8px 8px 0;color:var(--muted)}
</style>
</head>
<body><main>
<div class="eyebrow">Tuner Daemon · release ${evidence.release}</div>
<h1>UX quality dashboard</h1>
<p>Evidence for the gates. Metrics are generated from <code>docs/quality-evidence.json</code>; update the evidence file from the test run, then regenerate this page. Missing human evidence is shown as "—", not guessed.</p>
<div class="note">Updated ${evidence.updated}. The dashboard is generated by <code>npm run quality:dashboard</code>.</div>

<h2>Metrics</h2>
<div class="grid">
${card('Initial CSS', pct(m.initialCssReduction) + ' down', 'Gate 1 floor is 20%')}
${card('Duplicate CSS rules', m.duplicateCssRules, 'must be 0')}
${card('Unit tests', m.unitTests, 'design tokens, contrast, services')}
${card('E2E', `${m.e2ePassed} passed`, `${m.e2eSkipped} skipped`)}
${card('Axe serious/critical', m.axeSeriousCritical, 'per screen')}
${card('Lighthouse a11y', m.lighthouseAccessibility, 'Watch / Login')}
${card('Guide p95 frame', m.guideP95FrameMs + ' ms', '1,000+ channel fixture')}
${card('Theme switch', m.themeSwitchMs + ' ms', 'CI guard, not reference hardware')}
${card('First sync', m.firstSyncSeconds + ' s', 'synthetic, 60 channels')}
${card('SUS', m.sus ?? '—', m.sus === null ? 'needs participants' : 'target ≥80')}
${card('Task success', m.taskSuccess === null ? '—' : pct(m.taskSuccess), m.taskSuccess === null ? 'needs participants' : 'target ≥85%')}
</div>

<h2>Gates</h2>
<table><thead><tr><th>Gate</th><th>Status</th><th>Evidence</th></tr></thead><tbody>
${evidence.gates.map(g => `<tr><td><strong>${g.name}</b></td><td><span class="pill ${statusClass(g.status)}">${g.status}</span></td><td>${g.detail}</td></tr>`).join('')}
</tbody></table>

<h2>Open and closed findings</h2>
<table><thead><tr><th>Severity</th><th>Finding</th><th>Status</th></tr></thead><tbody>
${evidence.findings.map(f => `<tr><td>${f.severity}</td><td>${f.title}</td><td><span class="pill ${statusClass(f.status)}">${f.status}</span></td></tr>`).join('')}
</tbody></table>

<h2>How this stays honest</h2>
<p><code>npm run css:audit</code>, <code>npm test</code>, the Playwright projects (e2e, tv, visual) and Lighthouse are the sources. A metric is only marked pass when a test or a signed scorecard supports it; the human research rows stay empty until the sessions happen. Regenerate after every release and attach the page to the release notes.</p>
</main></body></html>`;

fs.writeFileSync(path.join(root, 'docs/quality-dashboard.html'), html);
console.log('Wrote docs/quality-dashboard.html');
